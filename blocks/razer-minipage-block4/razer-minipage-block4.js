function escapeHTML(value = '') {
  const replacements = {
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#039;',
  };
  return String(value).replace(/[&<>"']/g, (character) => replacements[character]);
}
function formatMessage(pattern = '', values = {}) {
  return String(pattern).replace(/\{(\w+)\}/g, (match, key) => (Object.hasOwn(values, key) ? values[key] : match));
}
export function normalizeKey(value = '') {
  return value.trim().toLowerCase().replace(/\s+/g, '-');
}
function renderImage(image, options = {}) {
  const {
    className = '',
    eager = false,
    decorative = false,
    thumbnail = false,
  } = options;
  const classAttribute = className ? ` class="${escapeHTML(className)}"` : '';
  const alt = decorative ? '' : image.alt;
  const priority = eager ? ' fetchpriority="high"' : '';
  const loading = eager ? 'eager' : 'lazy';
  const src = thumbnail ? image.thumbnail || image.src : image.src;
  const width = thumbnail ? 78 : image.width;
  const height = thumbnail ? 78 : image.height;
  const sources = !thumbnail && Array.isArray(image.sources) ? image.sources : [];
  const sourceMarkup = sources.map((source) => `<source
    srcset="${escapeHTML(source.srcset)}"
    ${source.media ? `media="${escapeHTML(source.media)}"` : ''}
    ${source.sizes ? `sizes="${escapeHTML(source.sizes)}"` : ''}
    ${source.type ? `type="${escapeHTML(source.type)}"` : ''}
    ${source.width ? `width="${source.width}"` : ''}
    ${source.height ? `height="${source.height}"` : ''}>`).join('');
  const rendered = `<img${classAttribute}
    src="${escapeHTML(src)}"
    alt="${escapeHTML(alt)}"
    width="${width}"
    height="${height}"
    loading="${loading}"
    decoding="async"${priority}>`;
  return sourceMarkup ? `<picture>${sourceMarkup}${rendered}</picture>` : rendered;
}
